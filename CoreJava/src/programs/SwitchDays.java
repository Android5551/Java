package programs;

public class SwitchDays {

	public static void main(String[] args) {
		// TODO Weekdays
		String day = "Sunday";
		switch (day) {
			case "Monday":
				System.out.println("Weekday 1");
				break;
			case "Tuesday":
				System.out.println("Weekday 2");
				break;
			case "Wednesday":
				System.out.println("Weekday 3");
				break;
			case "Thursday":
				System.out.println("Weekday 4");
				break;
			case "Friday":
				System.out.println("Weekday 5");
				break;
			case "Saturday":
				System.out.println("Weekday 6");
				break;
			case "Sunday":
				System.out.println("Weekend");
				break;
			default:
				System.out.println("Please enter a valid Weekday!");
			
			
			

	}

}
}
