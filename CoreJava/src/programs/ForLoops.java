package programs;

public class ForLoops {
	public static void main(String[] args) {
		// increment
		System.out.println("Increment from 0 to 9");
		for(int i = 0; i < 10; i++) {
			System.out.println(i);
		}
		
		// decrement
		System.out.println("Decrement from 10 to 1");
		for(int i = 10; i > 0; i--) {
			System.out.println(i);
		}
	
	}
}
